/* Dev-time generator for the RFC document area. Not part of the site runtime.
 *
 * Reads the verbatim rfc-editor copies under rfc/source/ and writes:
 *
 *   - rfc/<number>/index.html          one landing page per document, carrying
 *     everything before the first numbered heading (title page, abstract,
 *     status of this memo, table of contents, copyright block);
 *   - rfc/<number>/<section path>/     one page per section of the document,
 *     index.html                holding exactly one <pre> with the section's
 *     byte range from the source, entity-escaped and otherwise untouched;
 *   - _data/rfc-sources.json           the metadata the layouts render from:
 *     source URL, retrieval date, SHA-256, the document title read from the
 *     copy itself, and the section index (number, title, path, byte range).
 *
 * Sections are cut on the numbered headings in the body, never on the table of
 * contents: a missed heading merges into the previous section, so the text is
 * still complete (see the coverage assertion). The table of contents is parsed
 * only to cross-check the cut and report differences as warnings.
 *
 * Run: node tools/build-rfc-pages.mjs
 *      node tools/build-rfc-pages.mjs --check
 * Env: RFC_EXPORT_DIR writes and compares against that directory instead of the
 *      repository, for development-time drift cases only.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import process from 'node:process';

const REPO = dirname(import.meta.dirname);
const OUTPUT_ROOT = process.env.RFC_EXPORT_DIR || REPO;
const DATA_FILE = join('_data', 'rfc-sources.json');
const CHECK = process.argv.includes('--check');

const GENERATED_NOTE = 'Generated by tools/build-rfc-pages.mjs. Do not edit by hand: the pages under rfc/ and the section index below are produced from the verbatim copies in rfc/source/, and tools/check-rfc-fidelity.mjs proves they are still those bytes.';

const DOCS = [
  {
    rfc: 8299,
    url: 'https://www.rfc-editor.org/rfc/rfc8299.txt',
    infoUrl: 'https://www.rfc-editor.org/info/rfc8299',
    retrieved: '2026-10-31',
    navOrder: 3,
  },
  {
    rfc: 9182,
    url: 'https://www.rfc-editor.org/rfc/rfc9182.txt',
    infoUrl: 'https://www.rfc-editor.org/info/rfc9182',
    retrieved: '2026-10-31',
    navOrder: 4,
  },
];

const HEADING_PATTERNS = [
  /* 6.3.2.2.  Two spaces after the number, title starting at column 0. */
  /^(\d+(?:\.\d+)*)\. {2,}(\S.*?)$/,
  /* Appendix A.  and its sub-headings A.1. */
  /^Appendix ([A-Z])\. {2,}(\S.*?)$/,
  /^([A-Z])\.(\d+(?:\.\d+)*)\. {2,}(\S.*?)$/,
];

function parseHeading(line) {
  let match = HEADING_PATTERNS[0].exec(line);
  if (match) {
    return { kind: 'num', num: match[1], letter: null, parts: match[1].split('.').map(Number), title: match[2].trim() };
  }
  match = HEADING_PATTERNS[1].exec(line);
  if (match) {
    return { kind: 'apx', num: `Appendix ${match[1]}`, letter: match[1], parts: [], title: match[2].trim() };
  }
  match = HEADING_PATTERNS[2].exec(line);
  if (match) {
    return { kind: 'apx', num: `${match[1]}.${match[2]}`, letter: match[1], parts: match[2].split('.').map(Number), title: match[3].trim() };
  }
  return null;
}

/* A heading continues the sequence when it is the next sibling of the current
 * one at some level, or its first child — 1.4.2 -> 1.4.3, 1.4.2 -> 2,
 * 6.2 -> 6.2.1 all qualify, 6.2 -> 6.2.3 or 6.2.4 -> 6 do not. Anything that
 * fails this is a numbered line inside a figure or a list and is skipped, so a
 * missed real heading can only ever merge into the page before it. */
function isContinuation(previous, candidate) {
  if (!previous) { return candidate.kind === 'num' && candidate.parts.length === 1 && candidate.parts[0] === 1; }
  if (previous.kind !== candidate.kind) { return candidate.kind === 'apx' && candidate.letter === 'A'; }
  if (candidate.kind === 'apx' && previous.letter !== candidate.letter) {
    return candidate.parts.length === 0 || (candidate.parts.length === 1 && candidate.parts[0] === 1);
  }
  for (let depth = 1; depth <= previous.parts.length + 1; depth++) {
    if (depth > candidate.parts.length) { break; }
    const sharesPrefix = candidate.parts.slice(0, depth - 1).every((value, index) => value === previous.parts[index]);
    if (!sharesPrefix) { continue; }
    if (candidate.parts[depth - 1] === (previous.parts[depth - 1] ?? 0) + 1) { return true; }
  }
  return false;
}

function lineOffsets(buffer) {
  const lines = buffer.toString('utf8').split('\n');
  const offsets = [];
  let acc = 0;
  for (const line of lines) {
    offsets.push(acc);
    acc += Buffer.byteLength(line, 'utf8') + 1;
  }
  return { lines, offsets };
}

function splitDocument(buffer) {
  const { lines, offsets } = lineOffsets(buffer);
  const headings = [];
  let previous = null;
  lines.forEach((line, index) => {
    const heading = parseHeading(line);
    if (!heading) { return; }
    if (!isContinuation(previous, heading)) { return; }
    previous = heading;
    headings.push({ ...heading, line: index });
  });
  if (headings.length === 0) { throw new Error('no headings found; the source does not look like an RFC'); }
  if (headings.at(-1).line + 1 >= lines.length) { throw new Error('the last heading reaches the end of the file'); }
  const sections = headings.map((heading, index) => {
    const start = offsets[heading.line];
    const end = index + 1 < headings.length ? offsets[headings[index + 1].line] : buffer.length;
    return { ...heading, start, end, path: pathOf(heading) };
  });
  return { lines, sections, preambleEnd: sections[0].start };
}

function pathOf(heading) {
  if (heading.letter) {
    return heading.parts ? `${heading.letter.toLowerCase()}-${heading.parts.join('-')}` : `appendix-${heading.letter.toLowerCase()}`;
  }
  return heading.num.replace(/\./g, '-');
}

/* The copy is published verbatim, so nothing here changes a byte of it: these
 * are the HTML escapes that keep the text intact through the browser, plus a
 * numeric reference for the characters a document pipeline is most likely to
 * drop (the page separator and the byte-order mark). */
function escapeBody(text) {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\f/g, '&#12;')
    .replace(/\uFEFF/g, '&#65279;');
}

function page(frontMatter, body) {
  return `---\n${frontMatter}\n---\n<pre>${body}</pre>\n`;
}

function yamlQuote(value) {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

function titleOf(buffer, lines) {
  const abstract = lines.findIndex((line) => /^Abstract/.test(line.trim()));
  if (abstract < 0) { throw new Error('no Abstract marker; cannot find the document title'); }
  let end = abstract - 1;
  while (end >= 0 && lines[end].trim() === '') { end--; }
  let start = end;
  while (start > 0 && lines[start - 1].trim() !== '') { start--; }
  if (end < start || start < 2) { throw new Error('the title block above Abstract is empty'); }
  return lines.slice(start, end + 1).map((line) => line.trim()).join(' ');
}

/* The legal block the page shell quotes: from the document's own
 * "Copyright Notice" heading to the last line before "Table of Contents". It is
 * read out of the copy rather than typed, and its byte range is recorded so the
 * fidelity checker can prove the quote is still those bytes. */
function noticeOf(buffer) {
  const text = buffer.toString('utf8');
  const marker = text.indexOf('\nCopyright Notice\n');
  if (marker < 0) { throw new Error('no Copyright Notice block; the shell would have nothing to quote'); }
  const from = marker + 1;
  const toc = text.indexOf('\nTable of Contents\n', from);
  if (toc < 0) { throw new Error('no Table of Contents heading after the copyright block'); }
  let end = toc;
  while (text[end - 1] === '\n') { end--; }
  return {
    start: Buffer.byteLength(text.slice(0, from), 'utf8'),
    end: Buffer.byteLength(text.slice(0, end), 'utf8'),
    html: escapeBody(text.slice(from, end)),
  };
}

/* Best effort: both table-of-contents styles are read, only to report what the
 * body cut disagreed with. */
function tocNumbers(lines) {
  const start = lines.findIndex((line) => /^Table of Contents\s*$/.test(line));
  if (start < 0) { return null; }
  const found = [];
  for (let index = start + 1; index < lines.length; index++) {
    const line = lines[index];
    if (/^\d+(?:\.\d+)*\. {2,}\S/.test(line) || /^Appendix [A-Z]\. {2,}\S/.test(line)) { break; }
    let match = /^ +(?:(\d+(?:\.\d+)*)|Appendix ([A-Z])|([A-Z])\.(\d+(?:\.\d+)*))\.? {1,}.*$/.exec(line);
    if (!match) { continue; }
    if (match[1]) { found.push({ num: match[1], line: index }); }
    else if (match[2]) { found.push({ num: `Appendix ${match[2]}`, letter: match[2], line: index }); }
    else { found.push({ num: `${match[3]}.${match[4]}`, letter: match[3], parts: match[4].split('.').map(Number), line: index }); }
  }
  return found;
}

function crossCheck(name, lines, sections) {
  const toc = tocNumbers(lines);
  if (!toc) { return [`${name}: no table of contents found, nothing to cross-check`]; }
  const body = new Set(sections.map((section) => section.num));
  const cut = new Set(toc.map((entry) => entry.num));
  const warnings = [];
  const listed = [];
  for (const entry of toc) {
    if (!body.has(entry.num)) { listed.push(`§${entry.num} (line ${entry.line + 1})`); }
  }
  /* The risky direction: the document advertises a section this cut has no page
   * for, which means a heading was skipped and its text merged into the page
   * before it. */
  if (listed.length) {
    warnings.push(`${name}: the table of contents lists ${listed.length} section(s) with no page of their own: ${listed.join(', ')}`);
  }
  /* The harmless direction: some RFCs abbreviate their own table of contents —
   * RFC 8299 leaves every fourth-level heading out of it — so a deeper page
   * than the contents list is a property of the document, not of this cut. */
  const extra = sections.filter((section) => !cut.has(section.num)).length;
  if (extra) {
    warnings.push(`${name}: ${extra} section(s) have a page but no table-of-contents entry (the document abbreviates its own contents list; the body headings are the source of truth)`);
  }
  return warnings;
}

function build() {
  const outputs = new Map();
  const data = { _generated: GENERATED_NOTE, docs: [] };
  const warnings = [];
  for (const doc of DOCS) {
    const sourceFile = join('rfc', 'source', `rfc${doc.rfc}.txt`);
    const buffer = readFileSync(join(REPO, sourceFile));
    const { lines, sections, preambleEnd } = splitDocument(buffer);
    warnings.push(...crossCheck(`RFC ${doc.rfc}`, lines, sections));
    const landing = `rfc/${doc.rfc}`;
    outputs.set(`${landing}/index.html`, page(
      [
        `title: ${yamlQuote(`RFC ${doc.rfc}: ${titleOf(buffer, lines)}`)}`,
        'layout: rfc-landing',
        `nav_order: ${doc.navOrder}`,
      ].join('\n'),
      escapeBody(buffer.subarray(0, preambleEnd).toString('utf8')),
    ));
    for (const section of sections) {
      const body = buffer.subarray(section.start, section.end).toString('utf8');
      const frontMatter = [
        `title: ${yamlQuote(sectionHeading(doc.rfc, section))}`,
        'layout: rfc-page',
        'nav_exclude: true',
      ].join('\n');
      outputs.set(`${landing}/${section.path}/index.html`, page(frontMatter, escapeBody(body)));
    }
    data.docs.push({
      rfc: doc.rfc,
      url: doc.url,
      infoUrl: doc.infoUrl,
      retrieved: doc.retrieved,
      sourceFile,
      sha256: createHash('sha256').update(buffer).digest('hex'),
      bytes: buffer.length,
      title: titleOf(buffer, lines),
      landingPath: `${landing}/index.html`,
      landingUrl: `/${landing}/`,
      landingTitle: `RFC ${doc.rfc}: ${titleOf(buffer, lines)}`,
      navOrder: doc.navOrder,
      notice: noticeOf(buffer),
      sections: sections.map((section) => ({
        num: section.num,
        title: section.title,
        path: section.path,
        pagePath: `${landing}/${section.path}/index.html`,
        pageUrl: `/${landing}/${section.path}/`,
        start: section.start,
        end: section.end,
      })),
    });
  }
  outputs.set(DATA_FILE, `${JSON.stringify(data, null, 2)}\n`);
  return { outputs, data, warnings };
}

function sectionHeading(rfc, section) {
  return section.letter
    ? `RFC ${rfc} ${section.num} ${section.title}`
    : `RFC ${rfc} §${section.num} ${section.title}`;
}

function coverage(data, outputs) {
  const problems = [];
  for (const doc of data.docs) {
    const buffer = readFileSync(join(REPO, doc.sourceFile));
    /* The landing page carries everything before the first heading, so the
     * chain starts where that block ends. */
    let expected = doc.sections[0].start;
    const bodies = [buffer.subarray(0, doc.sections[0].start).toString('utf8')];
    for (const section of doc.sections) {
      if (section.start !== expected) {
        problems.push(`RFC ${doc.rfc} §${section.num}: gap or overlap at byte ${expected} (section starts at ${section.start})`);
      }
      expected = section.end;
      bodies.push(buffer.subarray(section.start, section.end).toString('utf8'));
    }
    if (expected !== buffer.length) {
      problems.push(`RFC ${doc.rfc}: the last section ends at ${expected}, the file is ${buffer.length} bytes`);
    }
    const joined = bodies.map(escapeBody).join('');
    const rendered = [outputs.get(doc.landingPath)]
      .concat(doc.sections.map((section) => outputs.get(section.pagePath)))
      .map((pageText) => {
        const start = pageText.indexOf('<pre>') + '<pre>'.length;
        return pageText.slice(start, pageText.lastIndexOf('</pre>'));
      })
      .join('');
    if (rendered !== joined) {
      problems.push(`RFC ${doc.rfc}: the pages as generated are not the escaped source back to back`);
    }
    const hash = createHash('sha256').update(buffer).digest('hex');
    if (hash !== doc.sha256 || buffer.length !== doc.bytes) {
      problems.push(`RFC ${doc.rfc}: the copy on disk no longer matches its recorded checksum`);
    }
    const quoted = buffer.subarray(doc.notice.start, doc.notice.end).toString('utf8');
    if (escapeBody(quoted) !== doc.notice.html) {
      problems.push(`RFC ${doc.rfc}: the recorded copyright quote is not source bytes ${doc.notice.start}..${doc.notice.end}`);
    }
  }
  return problems;
}

const { outputs, data, warnings } = build();
const problems = coverage(data, outputs);
if (problems.length) {
  for (const problem of problems) { console.error(`FAIL ${problem}`); }
  process.exit(1);
}

let drift = [];
if (CHECK) {
  const labels = new Map();
  for (const doc of data.docs) {
    labels.set(doc.landingPath, `RFC ${doc.rfc} landing page (preamble)`);
    for (const section of doc.sections) labels.set(section.pagePath, `RFC ${doc.rfc} §${section.num}`);
  }
  const labelOf = (path) => labels.get(path) ?? (path === DATA_FILE ? 'the generated section index' : path);
  for (const [path, text] of outputs) {
    const onDisk = existsSync(join(OUTPUT_ROOT, path)) ? readFileSync(join(OUTPUT_ROOT, path), 'utf8') : null;
    if (onDisk === null) { drift.push(`${labelOf(path)}: ${path} is missing`); }
    else if (onDisk !== text) { drift.push(`${labelOf(path)}: ${path} differs from what the source produces`); }
  }
  const extra = listGenerated(join(OUTPUT_ROOT, 'rfc')).filter((path) => !outputs.has(path));
  drift.push(...extra.map((path) => `${path} was not produced by the last run`));
} else {
  for (const [path, text] of outputs) {
    const target = join(OUTPUT_ROOT, path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, text);
  }
}

const total = data.docs.reduce((sum, doc) => sum + doc.sections.length, 0);
console.log(`rfc pages: ${total} section pages + ${data.docs.length} landing pages, ${data.docs.map((doc) => `${doc.rfc}:${doc.sections.length}`).join(' ')}, coverage gap 0`);
for (const warning of warnings) { console.log(`warn ${warning}`); }
if (CHECK) {
  if (drift.length) {
    for (const line of drift) { console.error(`DRIFT ${line}`); }
    console.error(`build-rfc-pages --check: ${drift.length} file(s) out of step with rfc/source/`);
    process.exit(1);
  }
  console.log(`build-rfc-pages --check: ${outputs.size} generated files match rfc/source/`);
}

function listGenerated(root) {
  const found = [];
  if (!existsSync(root)) { return found; }
  const walk = (directory) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      const path = join(directory, entry.name);
      if (entry.isDirectory()) { walk(path); }
      else if (entry.name.endsWith('.html')) { found.push(relative(OUTPUT_ROOT, path)); }
    }
  };
  walk(root);
  return found;
}
